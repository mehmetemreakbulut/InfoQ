import torch.nn as nn

class VGGAutoEncoderWithLatentFC(nn.Module):
    def __init__(self, encoder, decoder, latent_dim=512, img_size=224):
        super(VGGAutoEncoderWithLatentFC, self).__init__()
        self.encoder = encoder
        self.decoder = decoder

        # Calculate the input size for the fully connected layer
        # Assuming the encoder's last output is 512 channels and spatial dimensions are img_size / 32
        encoder_output_spatial_dim = img_size // 32 # VGG has 5 maxpool layers, 2^5 = 32
        fc_input_features = encoder_output_spatial_dim * encoder_output_spatial_dim * 512

        self.fc = nn.Sequential(
            nn.Flatten(),
            nn.Linear(in_features=fc_input_features, out_features=latent_dim),
            nn.ReLU(inplace=True)
        )

        # Linear layer to expand the latent representation back to the original spatial dimensions for the decoder
        self.expand_latent = nn.Linear(in_features=latent_dim, out_features=fc_input_features)
        self.relu = nn.ReLU(inplace=True)

        # Store the spatial dimensions for reshaping
        self.decoder_input_reshape = (512, encoder_output_spatial_dim, encoder_output_spatial_dim)


    def forward(self, x):
        x = self.encoder(x)
        x = self.fc(x)
        x = self.expand_latent(x)
        x = self.relu(x)
        # Reshape the expanded latent representation back to spatial
        x = x.view(x.size(0), *self.decoder_input_reshape)
        x = self.decoder(x)
        return x



